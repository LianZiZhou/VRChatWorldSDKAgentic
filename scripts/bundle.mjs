#!/usr/bin/env node
/**
 * Produces the committed build artifacts in `bundled/`.
 *
 * The point is that a fresh clone works without `npm install`. The two Node programs here have real
 * dependencies (the MCP SDK, zod), and asking whoever imports this toolchain to resolve them first puts a
 * package registry between them and a working editor bridge — on a machine that may well be offline, or
 * behind a registry mirror that does not have them.
 *
 * So dependencies are inlined at release time and the result is committed. The per-package dist
 * directories stay the development output; `bundled/` is what ships.
 *
 * Run: node scripts/bundle.mjs
 */
import { build } from "esbuild";
import { mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { hashSources } from "./source-hash.mjs";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(repo, "bundled");
mkdirSync(out, { recursive: true });

const targets = [
  { entry: "packages/vrcw-mcp/src/index.ts", outfile: "vrcw-mcp.mjs", name: "MCP server" },
  { entry: "packages/supervisor/src/index.ts", outfile: "vrcw-supervisor.mjs", name: "supervisor CLI" },
];

const banner = [
  "// Generated by scripts/bundle.mjs — do not edit.",
  "// Source of truth: packages/*/src. Rebuild with: node scripts/bundle.mjs",
].join("\n");

for (const target of targets) {
  const outfile = join(out, target.outfile);
  await build({
    entryPoints: [join(repo, target.entry)],
    outfile,
    bundle: true,
    platform: "node",
    target: "node20",
    format: "esm",
    sourcemap: false,
    legalComments: "inline",
    banner: { js: banner },
    logLevel: "warning",
  });
  const kb = Math.round(statSync(outfile).size / 1024);
  console.log(`${target.name.padEnd(14)} -> bundled/${target.outfile} (${kb}KB)`);
}

// Record what produced these, so a stale bundle is diagnosable rather than mysterious.
const versions = {};
for (const pkg of ["vrcw-mcp", "supervisor"]) {
  const manifest = JSON.parse(readFileSync(join(repo, "packages", pkg, "package.json"), "utf8"));
  versions[manifest.name] = manifest.version;
}

// A content hash of the sources, not a timestamp.
//
// Staleness has to be answerable after a fresh clone, where every file carries the same checkout mtime, and
// the stamp should not change when nothing did — a timestamp makes this file churn on every rebuild and
// still cannot tell a clone whether the bundle matches its sources. scripts/install.mjs recomputes this and
// warns on a mismatch, which is the one failure this layout introduces: .mcp.json points at bundled/, so an
// unbundled edit means the running server is not the code being read.
writeFileSync(
  join(out, "BUNDLE.json"),
  JSON.stringify({ node: process.version, versions, sourcesSha256: hashSources(repo) }, null, 2) + "\n",
  "utf8"
);
console.log("manifest       -> bundled/BUNDLE.json");
